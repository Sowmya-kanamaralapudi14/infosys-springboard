import pandas as pd
import numpy as np

from sklearn.preprocessing import LabelEncoder
from sklearn.metrics import mean_absolute_error, mean_squared_error

import xgboost as xgb
import lightgbm as lgb

import matplotlib.pyplot as plt

df = pd.read_csv("/content/revenue_lift_9pct_30000.csv")

print("Dataset Shape:", df.shape)
df.head()

"""Basic Cleaning (no missing values)"""

print("Missing values before:")
print(df.isna().sum())

df = df.dropna().reset_index(drop=True)

print("\nMissing values after:")
print(df.isna().sum())

"""Data conversion & sorting"""

df['Date'] = pd.to_datetime(df['Date'])
df = df.sort_values('Date')

df[['Date']].head()

"""Encode Categorical columns"""

cat_cols = df.select_dtypes(include=['object']).columns
print("Categorical Columns:", cat_cols)

for col in cat_cols:
    le = LabelEncoder()
    df[col] = le.fit_transform(df[col].astype(str))

df.head()

"""features"""

X = df.drop(columns=['Units Sold'])
y = df['Units Sold']

print("X shape:", X.shape)
print("y shape:", y.shape)

"""Time-based train-test split"""

split_index = int(len(df) * 0.8)

X_train = X.iloc[:split_index]
X_test  = X.iloc[split_index:]

y_train = y.iloc[:split_index]
y_test  = y.iloc[split_index:]

print("Train size:", X_train.shape)
print("Test size :", X_test.shape)

"""train XGBoot Model"""

xgb_model = xgb.XGBRegressor(
    n_estimators=200,
    learning_rate=0.1,
    random_state=42
)

# Fix: Drop the 'Date' column which is of datetime type, as XGBoost cannot handle it directly.
# For a more robust solution, features like year, month, day, etc., could be extracted
# from the 'Date' column earlier in the data preprocessing.
if 'Date' in X_train.columns:
    X_train = X_train.drop('Date', axis=1)
if 'Date' in X_test.columns:
    X_test = X_test.drop('Date', axis=1)

xgb_model.fit(X_train, y_train)

print(" XGBoost training completed")

xgb_model = xgb.XGBRegressor(random_state=42)
xgb_model.fit(X_train, y_train)

xgb_pred = xgb_model.predict(X_test)

xgb_mae = mean_absolute_error(y_test, xgb_pred)
xgb_rmse = np.sqrt(mean_squared_error(y_test, xgb_pred))

print("XGBoost MAE :", round(xgb_mae, 2))
print("XGBoost RMSE:", round(xgb_rmse, 2))

"""train lightGBM model"""

lgb_model = lgb.LGBMRegressor(
    n_estimators=200,
    learning_rate=0.1,
    random_state=42
)

lgb_model.fit(X_train, y_train)

print(" LightGBM training completed")

lgb_model = lgb.LGBMRegressor(random_state=42)
lgb_model.fit(X_train, y_train)

lgb_pred = lgb_model.predict(X_test)

lgb_mae = mean_absolute_error(y_test, lgb_pred)
lgb_rmse = np.sqrt(mean_squared_error(y_test, lgb_pred))

print("LightGBM MAE :", round(lgb_mae, 2))
print("LightGBM RMSE:", round(lgb_rmse, 2))

"""model predictions"""

xgb_pred = xgb_model.predict(X_test)
lgb_pred = lgb_model.predict(X_test)

"""model evaluation (RMSE & MEA)"""

def evaluate(y_true, y_pred, name):
    mae = mean_absolute_error(y_true, y_pred)
    rmse = np.sqrt(mean_squared_error(y_true, y_pred))
    print(f"\n{name}")
    print("MAE :", round(mae, 2))
    print("RMSE:", round(rmse, 2))

evaluate(y_test, xgb_pred, "XGBoost")
evaluate(y_test, lgb_pred, "LightGBM")

"""prepare test data for backtesting"""

df_test = df.iloc[split_index:].copy()
df_test['Predicted_Demand'] = xgb_pred

df_test[['Predicted_Demand']].head()

"""ML Based Dynamic pricing Logic"""

avg_demand = df_test['Predicted_Demand'].mean()

df_test['ML_Price'] = np.where(
    df_test['Predicted_Demand'] > avg_demand,
    df_test['Price'] * 1.05,   # increase
    df_test['Price'] * 0.95    # decrease
)

df_test[['Price','ML_Price']].head()

"""Revenu calculation"""

df_test['Static_Revenue'] = df_test['Price'] * df_test['Units Sold']
df_test['ML_Revenue'] = df_test['ML_Price'] * df_test['Units Sold']

static_revenue = df_test['Static_Revenue'].sum()
ml_revenue = df_test['ML_Revenue'].sum()

print("Static Revenue:", round(static_revenue,2))

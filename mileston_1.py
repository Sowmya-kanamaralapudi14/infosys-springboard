import pandas as pd
import numpy as np
import os


filename = "/content/master_dataset_cleaned.csv"
if not os.path.exists(filename):
    raise FileNotFoundError(f"File not found: {filename}. Put the CSV in the same folder or update path.")

df = pd.read_csv(filename)
print("Loaded file. Columns:", list(df.columns))


df.columns = [c.strip() for c in df.columns]


numeric_cols = ['Units Sold','Price','Cost Price','Revenue','Stock Level']
for c in numeric_cols:
    if c in df.columns:
        df[c] = pd.to_numeric(df[c], errors='coerce')


if 'Revenue' not in df.columns or df['Revenue'].isnull().all():
    if 'Units Sold' in df.columns and 'Price' in df.columns:
        df['Revenue'] = df['Units Sold'] * df['Price']
    else:
        df['Revenue'] = np.nan
        print("Warning: cannot compute Revenue — 'Units Sold' or 'Price' missing")


if 'Cost Price' in df.columns:
    df['Profit'] = df['Revenue'] - (df['Units Sold'] * df['Cost Price'])
else:
    df['Profit'] = np.nan
    print("Warning: 'Cost Price' missing — Profit set to NaN")


df['Profit_Margin_pct'] = np.where(df['Revenue']>0, (df['Profit']/df['Revenue'])*100, 0)


if 'Stock Level' in df.columns:

    df['Inventory_Turnover'] = df['Units Sold'] / df['Stock Level'].replace({0: np.nan})
else:
    df['Inventory_Turnover'] = np.nan
    print("Note: 'Stock Level' missing — inventory turnover not computed")


if 'Pricing_Type' not in df.columns:
    print("Warning: 'Pricing_Type' column not found. Cannot compute baseline vs dynamic KPIs.")
else:

    revenue_baseline = df.loc[df['Pricing_Type'].str.lower()=='baseline','Revenue'].sum()
    revenue_dynamic  = df.loc[df['Pricing_Type'].str.lower()=='dynamic','Revenue'].sum()

    if revenue_baseline == 0:
        revenue_lift_pct = np.nan
        print("Revenue baseline is zero — cannot compute lift")
    else:
        revenue_lift_pct = ((revenue_dynamic - revenue_baseline) / revenue_baseline) * 100


    pm_baseline = df.loc[df['Pricing_Type'].str.lower()=='baseline','Profit_Margin_pct'].mean()
    pm_dynamic  = df.loc[df['Pricing_Type'].str.lower()=='dynamic','Profit_Margin_pct'].mean()


    it_baseline = df.loc[df['Pricing_Type'].str.lower()=='baseline','Inventory_Turnover'].mean()
    it_dynamic  = df.loc[df['Pricing_Type'].str.lower()=='dynamic','Inventory_Turnover'].mean()


    pm_improvement = (pm_dynamic - pm_baseline) if not (np.isnan(pm_baseline) and np.isnan(pm_dynamic)) else np.nan
    if pd.isna(it_baseline) or it_baseline == 0:
        it_improvement_pct = np.nan
    else:
        it_improvement_pct = ((it_dynamic - it_baseline) / it_baseline) * 100


    print("Revenue Lift (%):", round(float(revenue_lift_pct),2) if pd.notna(revenue_lift_pct) else "NA")
    print("Profit Margin Improvement (%):", round(float(pm_improvement),2) if pd.notna(pm_improvement) else "NA")
    print("Inventory Turnover Improvement (%):", round(float(it_improvement_pct),2) if pd.notna(it_improvement_pct) else "NA")


outfn = "cleaned_with_kpis.csv"
df.to_csv(outfn, index=False)
print("Saved", outfn)


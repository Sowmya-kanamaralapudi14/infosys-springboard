import pandas as pd


data = pd.read_csv("master_dataset_cleaned.csv")

data.columns = data.columns.str.strip()


data['Date'] = pd.to_datetime(data['Date'], errors='coerce')
data['YEAR']  = data['Date'].dt.year
data['MONTH'] = data['Date'].dt.month
data['DAY']   = data['Date'].dt.day


data['Profit'] = data['Revenue'] - (data['Cost Price'] * data['Units Sold'])


data['Profit_Margin'] = data['Profit'] / data['Revenue']
data['Profit_Margin'] = data['Profit_Margin'].fillna(0)


if 'Stock Level' in data.columns:
    data['Inventory_Turnover'] = data['Units Sold'] / data['Stock Level']
else:
    print("Note: 'Stock Level' column ledu — Inventory Turnover compute cheyyaledu")


monthly = data.groupby(['Product ID','YEAR','MONTH'])['Revenue'].sum().reset_index()
monthly = monthly.sort_values(['Product ID','YEAR','MONTH'])
monthly['Revenue_prev_month'] = monthly.groupby('Product ID')['Revenue'].shift(1)
monthly['Revenue_lift_pct'] = (monthly['Revenue'] - monthly['Revenue_prev_month']) / monthly['Revenue_prev_month']
monthly['Revenue_lift_pct'] = monthly['Revenue_lift_pct'].fillna(0)


data = data.merge(monthly[['Product ID','YEAR','MONTH','Revenue_lift_pct']],
                  on=['Product ID','YEAR','MONTH'],
                  how='left')


print(data[['Product ID','Date','Units Sold','Price','Revenue','Profit','Profit_Margin','Inventory_Turnover','Revenue_lift_pct']].head())


data.to_csv("cleaned_with_kpis.csv", index=False)
print("Saved cleaned_with_kpis.csv")

